import type { IR, IRNode } from "../normalize/ir.js";
import { isTextChild } from "../normalize/ir.js";
import type { InteractionCapture } from "../capture/interactions.js";

/**
 * Stage 4 — script-driven hover controller. CSS `:hover` deltas are emitted
 * declaratively (interactionCss / Tailwind `hover:` variants); a hover the SOURCE
 * implements in script (Webflow IX2, Framer whileHover) has no CSS rule to emit and its
 * animated target may live outside the trigger's subtree, so it is reproduced by one
 * fixed `'use client'` controller, `DittoHover`, parameterized by captured end-state
 * styles. Mirrors the DittoWire contract: renders null and applies NOTHING on mount —
 * the base render is exactly the captured resting state — and toggles the captured
 * inline styles on pointerenter/pointerleave. Easing: the captured WAAPI timing when
 * the source exposed one, else the target's own animating transition, else a fixed
 * default — decided at runtime from constants, so no measured value ever reaches the
 * generated bytes.
 */

export type RTHoverTarget = { target: string; on: Record<string, string>; off: Record<string, string>; durationMs: number | null; easing: string | null };
export type RTHover = { trigger: string; targets: RTHoverTarget[] };
export type HoverSpec = { items: RTHover[] };

const capToCid = (ir: IR): Map<string, string> => {
  const m = new Map<string, string>();
  const walk = (n: IRNode): void => {
    const cap = n.attrs["data-cid-cap"];
    if (cap !== undefined) m.set(cap, n.id);
    for (const c of n.children) if (!isTextChild(c)) walk(c);
  };
  walk(ir.root);
  return m;
};

/** Resolve cap-keyed JS-hover captures to cids that survived into this IR (optionally
 *  scoped by an include filter). A trigger whose trigger element was pruned is dropped;
 *  a surviving trigger keeps only its surviving targets. */
export function buildHoverSpec(ir: IR, interaction: InteractionCapture | undefined, include?: (cid: string) => boolean): HoverSpec {
  const hovers = interaction?.hoverJs ?? [];
  if (!hovers.length) return { items: [] };
  const map = capToCid(ir);
  const ok = (cid: string | undefined): cid is string => !!cid && (!include || include(cid));
  const items: RTHover[] = [];
  for (const h of hovers) {
    const trigger = map.get(h.triggerCap);
    if (!ok(trigger)) continue;
    const targets: RTHoverTarget[] = [];
    for (const t of h.targets) {
      const cid = map.get(t.cap);
      if (!ok(cid) || !Object.keys(t.on).length) continue;
      targets.push({ target: cid, on: t.on, off: t.off, durationMs: t.durationMs, easing: t.easing });
    }
    if (targets.length) items.push({ trigger, targets });
  }
  items.sort((a, b) => a.trigger.localeCompare(b.trigger));
  return { items };
}

export function hoverHasContent(spec: HoverSpec): boolean {
  return spec.items.length > 0;
}

export function dittoHoverImportPath(depth: number): string {
  return (depth === 0 ? "./" : "../".repeat(depth)) + "ditto/DittoHover";
}

export function hoverWireJsx(spec: HoverSpec, indent: number): string {
  if (!hoverHasContent(spec)) return "";
  const pad = "  ".repeat(indent);
  return `${pad}<DittoHover spec={${JSON.stringify(spec)}} />`;
}

export const DITTO_HOVER_TSX = `"use client";
import { useEffect } from "react";

type RTHoverTarget = { target: string; on: Record<string, string>; off: Record<string, string>; durationMs: number | null; easing: string | null };
type RTHover = { trigger: string; targets: RTHoverTarget[] };
export type HoverSpec = { items: RTHover[] };

const byCid = (cid: string): HTMLElement | null => document.querySelector('[data-cid="' + cid + '"]');
const kebab = (p: string) => p.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());

// Replay easing when the source exposed no timing definition and the target has no
// animating transition of its own. Fixed constants — never captured or measured.
const DEFAULT_DURATION_MS = 250;
const DEFAULT_EASING = "cubic-bezier(0.165, 0.84, 0.44, 1)";

const animates = (t: string): boolean =>
  !!t && t.split(",").some((seg) => { const m = seg.match(/(\\d*\\.?\\d+)(ms|s)\\b/); return m ? parseFloat(m[1]) * (m[2] === "ms" ? 0.001 : 1) > 0 : false; });

/** Reproduces captured script-driven hover states (Webflow IX2 / Framer whileHover) by
 *  toggling captured end-state inline styles on pointerenter/pointerleave. Applies
 *  NOTHING on mount: the server-rendered markup already IS the captured resting state,
 *  so behavior is added without perturbing the base render. */
export default function DittoHover({ spec }: { spec: HoverSpec }) {
  useEffect(() => {
    const ac = new AbortController();
    const { signal } = ac;
    for (const item of spec.items) {
      const trig = byCid(item.trigger);
      if (!trig) continue;
      const apply = (state: "on" | "off") => {
        for (const t of item.targets) {
          const el = byCid(t.target);
          if (!el) continue;
          const own = getComputedStyle(el).transition;
          const transition = t.durationMs != null
            ? "all " + t.durationMs + "ms " + (t.easing || DEFAULT_EASING)
            : animates(own) ? own : "all " + DEFAULT_DURATION_MS + "ms " + DEFAULT_EASING;
          el.style.setProperty("transition", transition);
          const vals = state === "on" ? t.on : t.off;
          for (const k in vals) el.style.setProperty(kebab(k), vals[k]);
        }
      };
      trig.addEventListener("pointerenter", () => apply("on"), { signal });
      trig.addEventListener("pointerleave", () => apply("off"), { signal });
    }
    return () => ac.abort();
  }, [spec]);
  return null;
}
`;
